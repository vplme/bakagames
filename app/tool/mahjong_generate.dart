// Run from app/: dart run tool/mahjong_generate.dart
// Search and difficulty sampling happen here, never while opening a game.
import 'dart:convert';
import 'dart:io';
import 'dart:math';
import 'package:baka_games/games/mahjong/model.dart';
import 'package:baka_games/games/mahjong/levels.dart';

List<GardenTile> layout(int level) {
  final tier = level ~/ 6, variant = level % 6;
  final random = Random(19727 + level * 131);
  final rows = tier < 2 ? 5 : 6;
  final baseCount = [24, 26, 28, 30, 32][tier] + (variant % 3) * 2;
  final total = [24, 32, 40, 48, 56][tier] + (variant % 3) * 2;
  final height = [1, 2, 3, 3, 4][tier];
  final cells = <(int, int)>{(2, 2)};
  while (cells.length < baseCount) {
    final options = <(int, int)>[];
    for (var y = 0; y < rows; y++) {
      for (var x = 0; x < 6; x++) {
        if (cells.contains((x, y))) continue;
        if ([
          (x - 1, y),
          (x + 1, y),
          (x, y - 1),
          (x, y + 1),
        ].any(cells.contains)) {
          options.add((x, y));
        }
      }
    }
    options.shuffle(random);
    // Different directional biases produce winding, stepped and courtyard shapes.
    double score((int, int) p) => switch (variant) {
      0 => (p.$1 - p.$2).abs().toDouble(),
      1 => (p.$1 + p.$2 - 5).abs().toDouble(),
      2 => (p.$2 - 2).abs() + (p.$1 - 3).abs() * .25,
      3 => (p.$1 - 2).abs() + (p.$2 - 3).abs() * .25,
      4 => -((p.$1 - 2.5).abs() + (p.$2 - 2.5).abs()),
      _ => random.nextDouble() * 5,
    };
    // Score once: comparators must never consume randomness.
    final scores = {
      for (final p in options) p: score(p) + random.nextDouble() * 2,
    };
    options.sort((a, b) => scores[a]!.compareTo(scores[b]!));
    cells.add(options.first);
  }
  final coordinates = <(int, int, int)>[for (final p in cells) (p.$1, p.$2, 0)];
  if (height > 1) {
    final anchors =
        cells
            .where(
              (p) => p.$1 >= 1 && p.$1 <= 4 && p.$2 >= 1 && p.$2 < rows - 1,
            )
            .toList()
          ..shuffle(random);
    final anchor = anchors.first;
    for (var z = 1; z < height; z++) {
      coordinates.add((anchor.$1, anchor.$2, z));
    }
    while (coordinates.length < total) {
      final candidates = <(int, int, int)>[];
      for (var z = 1; z < height; z++) {
        for (final p in anchors) {
          if (coordinates.contains((p.$1, p.$2, z - 1)) &&
              !coordinates.contains((p.$1, p.$2, z))) {
            candidates.add((p.$1, p.$2, z));
          }
        }
      }
      candidates.shuffle(random);
      // Favor lower layers while preserving some taller, irregular stacks.
      candidates.sort((a, b) => a.$3.compareTo(b.$3));
      coordinates.add(candidates[random.nextInt(min(4, candidates.length))]);
    }
  }
  coordinates.sort(
    (a, b) => a.$3 != b.$3
        ? a.$3.compareTo(b.$3)
        : a.$2 != b.$2
        ? a.$2.compareTo(b.$2)
        : a.$1.compareTo(b.$1),
  );
  return [
    for (var i = 0; i < coordinates.length; i++)
      GardenTile(i, coordinates[i].$1, coordinates[i].$2, coordinates[i].$3, 0),
  ];
}

List<List<int>>? removalPath(List<GardenTile> slots, Random random) {
  final board = MahjongBoard.fromTiles(slots);
  final seen = <String>{};
  var visits = 0;
  bool visit() {
    if (board.won) return true;
    if (++visits > 12000) return false;
    final key = (board.removed.toList()..sort()).join(',');
    if (!seen.add(key)) return false;
    final options = board.legalPairs..shuffle(random);
    for (final pair in options) {
      board.match(pair[0], pair[1]);
      if (visit()) return true;
      board.undo();
    }
    return false;
  }

  return visit() ? board.history.map((p) => [...p]).toList() : null;
}

// An intentionally unplanned player, used as a relative difficulty proxy.
int randomWins(List<GardenTile> tiles, int trials, int seed) {
  final random = Random(seed);
  var wins = 0;
  for (var i = 0; i < trials; i++) {
    final b = MahjongBoard.fromTiles(tiles);
    while (!b.won) {
      final pairs = b.legalPairs;
      if (pairs.isEmpty) break;
      final pair = pairs[random.nextInt(pairs.length)];
      b.match(pair[0], pair[1]);
    }
    if (b.won) wins++;
  }
  return wins;
}

void main(List<String> args) {
  final output = StringBuffer(
    '''// Generated by tool/mahjong_generate.dart. Do not edit by hand.
class MahjongDealData {
  final List<List<int>> tiles, solution;
  final List<int> lanternTargets;
  const MahjongDealData(this.tiles, this.solution, [this.lanternTargets = const []]);
}
const mahjongDeals = <MahjongDealData>[\n''',
  );
  if (args.contains('--objectives-only')) {
    for (var level = 0; level < 30; level++) {
      final board = MahjongBoard.deal(level);
      writeDeal(output, board.tiles, board.solution, level);
    }
    output.writeln('];');
    File.fromUri(
      Platform.script.resolve('../lib/games/mahjong/deals.dart'),
    ).writeAsStringSync(output.toString());
    return;
  }
  final report = <Map<String, Object>>[];
  for (var level = 0; level < 30; level++) {
    final slots = layout(level);
    final tier = level ~/ 6;
    final target = [.88, .66, .44, .25, .10][tier] - (level % 6) * .015;
    final random = Random(82471 + level * 999);
    List<GardenTile>? best;
    List<List<int>>? bestPath;
    var bestDelta = double.infinity;
    for (var candidate = 0; candidate < 160; candidate++) {
      final path = removalPath(slots, random);
      if (path == null) continue;
      final palette = List.generate(11, (i) => i)..shuffle(random);
      final faceCount = [7, 8, 9, 9, 9][tier];
      final pairFaces = List.generate(
        path.length,
        (i) => palette[i % faceCount],
      )..shuffle(random);
      final faces = List.filled(slots.length, 0);
      for (var i = 0; i < path.length; i++) {
        for (final id in path[i]) {
          faces[id] = pairFaces[i];
        }
      }
      final tiles = [
        for (final t in slots) GardenTile(t.id, t.x, t.y, t.layer, faces[t.id]),
      ];
      // Never return to the old rule of assigning mirrored matching endpoints.
      var mirrored = 0, mirrors = 0;
      for (final a in tiles) {
        for (final b in tiles) {
          if (a.x < b.x && a.x + b.x == 5 && a.y == b.y && a.layer == b.layer) {
            mirrors++;
            if (a.face == b.face) mirrored++;
          }
        }
      }
      if (mirrors > 0 && mirrored / mirrors > .2) continue;
      final wins = randomWins(tiles, 64, 8101 + level);
      final delta = (wins / 64 - target).abs();
      if (delta < bestDelta) {
        best = tiles;
        bestPath = path;
        bestDelta = delta;
      }
      if (delta <= .025) break;
    }
    if (best == null) throw StateError('No calibrated deal for $level');
    final wins = randomWins(best, 256, 31001 + level);
    final b = MahjongBoard.fromTiles(best);
    report.add({
      'deal': level + 1,
      'tier': tier + 1,
      'tiles': best.length,
      'layers': b.layers,
      'openingPairs': b.legalPairs.length,
      'randomWins': wins,
      'trials': 256,
    });
    stdout.writeln(report.last);
    writeDeal(output, best, bestPath!, level);
  }
  output.writeln('];');
  File.fromUri(
    Platform.script.resolve('../lib/games/mahjong/deals.dart'),
  ).writeAsStringSync(output.toString());
  File.fromUri(
    Platform.script.resolve('../../docs/mahjong/difficulty-calibration.json'),
  ).writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(report)}\n',
  );
}

void writeDeal(
  StringBuffer output,
  List<GardenTile> tiles,
  List<List<int>> path,
  int level,
) {
  final targets = lanternTargets(tiles, path, mahjongLanternCount(level));
  output.writeln(
    '  // Deal ${level + 1}: tier ${level ~/ 6 + 1}, ${tiles.length} tiles.',
  );
  output.writeln('  MahjongDealData(');
  output.writeln(
    '    [${tiles.map((t) => '[${t.x},${t.y},${t.layer},${t.face}]').join(',')}],',
  );
  output.writeln('    [${path.map((p) => '[${p.join(',')}]').join(',')}],');
  output.writeln('    [${targets.join(',')}],');
  output.writeln('  ),');
}

List<int> lanternTargets(
  List<GardenTile> tiles,
  List<List<int>> path,
  int count,
) {
  if (count == 0) return [];
  final board = MahjongBoard.fromTiles(tiles);
  final covered = tiles
      .where(
        (t) => tiles.any((u) => u.x == t.x && u.y == t.y && u.layer > t.layer),
      )
      .map((t) => t.id)
      .toSet();
  final events = <List<int>>[];
  final seen = <int>{};
  for (final pair in path) {
    if (!board.match(pair[0], pair[1])) throw StateError('Invalid witness');
    final freed = covered
        .where((id) => !seen.contains(id) && board.isFree(id))
        .toList();
    if (freed.isNotEmpty) events.add(freed);
    seen.addAll(freed);
  }
  final targets = <int>[];
  final positions = <(int, int)>{};
  var previous = -1;
  for (var i = 0; i < count; i++) {
    var index = max(
      previous + 1,
      ((i + 1) * events.length / (count + 1)).floor(),
    );
    int? chosen;
    while (index < events.length && chosen == null) {
      for (final id in events[index]) {
        final tile = tiles[id];
        if (positions.add((tile.x, tile.y))) {
          chosen = id;
          break;
        }
      }
      if (chosen == null) index++;
    }
    if (chosen == null) throw StateError('Not enough distinct lantern reveals');
    targets.add(chosen);
    previous = index;
  }
  final check = MahjongBoard.fromTiles(tiles, lanternTargets: targets);
  for (final pair in path) {
    if (!check.match(pair[0], pair[1])) {
      throw StateError('Lanterns invalidate solution');
    }
  }
  if (!check.won) throw StateError('Lanterns cannot be completed');
  return targets;
}
